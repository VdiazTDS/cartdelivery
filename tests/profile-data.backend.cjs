const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { fixture } = require('./profile-data.fixture.cjs');

(async () => {
  const fx = await fixture();
  const { actor, call, pg, state, objects, read, importRows } = fx;
  try {
    const a = await actor('team_a'), b = await actor('team_b'), other = await actor('team_other');
    const rows = Array.from({ length: 5364 }, (_, index) => ({ ID: index, QTY: 3, ROUTE: 'A', DAY: 1,
      ...Object.fromEntries(Array.from({ length: 32 }, (_, col) => [`FIELD_${col}`, `Sample ${index}-${col}`])) }));
    const { fileId } = await importRows(a, 'Large.xlsx', rows);
    const copy = async user => (await pg.query('select * from cd_data_copies where file_id=$1 and owner_id=$2',[fileId,user.id])).rows[0];
    const original = async () => (await pg.query('select * from cd_data_files where id=$1',[fileId])).rows[0];
    const initialObjects = new Map(objects);
    const [oa,ob] = await Promise.all([call(a,'open',{fileId}),call(b,'open',{fileId})]);
    assert.equal(oa.lastSyncedAt, null, 'A new copy has no sync time');
    assert.notEqual(oa.copyId,ob.copyId);
    assert.equal((await pg.query('select count(*)::int n from cd_data_records')).rows[0].n,rows.length,'Copying does not duplicate source records');
    assert.equal(objects.size,initialObjects.size,'Opening copies does not rewrite Excel');
    const edit = (index,count) => ({ index,values:{del_qty:count,del_status:count===3?'Delivered':''} });
    const save = async (user,edits,extra={}) => call(user,'save',{fileId,copyRevision:(await copy(user)).revision,edits,...extra});
    await save(a,[edit(0,1),edit(2,1)]);
    await save(b,[edit(1,1),edit(2,1)]);
    assert.equal((await read(a,fileId))[0].del_qty,1);
    assert.equal((await read(b,fileId))[0].del_qty,null);
    assert.equal((await read(a,fileId,'original'))[0].del_qty,null);
    assert.equal(objects.size,initialObjects.size,'Saving never uploads Excel');
    await assert.rejects(()=>call(a,'save',{fileId,copyRevision:1,edits:[edit(0,2)]}),/STALE_VERSION/);
    await assert.rejects(()=>call(other,'save',{fileId,copyRevision:2,edits:[edit(0,2)]}),/COPY_NOT_FOUND/);
    await assert.rejects(()=>save(a,[{index:0,values:{QTY:20}}]),/INVALID_FIELDS/);
    await assert.rejects(()=>save(a,[edit(0,4)]),/INVALID_QUANTITY/);
    await assert.rejects(()=>save(a,[edit(0,2),edit(0,1)]),/INVALID_ROW/);
    const before = await copy(a);
    await assert.rejects(()=>save(a,[edit(0,2),edit(90000,1)]),/INVALID_ROW/);
    assert.equal((await copy(a)).revision,before.revision,'Invalid batch rolls back every change');
    assert.equal((await read(a,fileId))[0].del_qty,1);
    state.failCommit=true;
    await assert.rejects(()=>save(a,[edit(0,2)]),/Simulated commit failure/);
    state.failCommit=false;
    assert.equal((await copy(a)).revision,before.revision);
    const requestId=randomUUID();
    const request={fileId,copyRevision:before.revision,edits:[edit(0,2)],requestId};
    const saved=await call(a,'save',request);
    assert.deepEqual(await call(a,'save',request),saved,'Lost response retry applies once');
    await assert.rejects(()=>call(a,'save',{...request,edits:[edit(0,3)]}),/REQUEST_REUSED/);
    const preview=await call(a,'preview',{fileId});
    await call(a,'sync',{fileId,copyRevision:preview.copyRevision,masterRevision:preview.masterRevision,resolutions:[]});
    const syncedView = await call(a, 'open', { fileId });
    assert(Number.isFinite(Date.parse(syncedView.lastSyncedAt)), 'Sync time comes from confirmed history');
    assert.equal((await call(b, 'open', { fileId })).lastSyncedAt, null, 'Another profile does not inherit my sync time');
    assert.equal((await fx.handle({ action: 'public-original', fileId })).lastSyncedAt, null, 'Public views reveal no profile sync time');
    assert.equal((await original()).revision,2);
    assert.equal((await read(b,fileId))[0].del_qty,null,'Other copy retains its baseline until sync');
    const overlap=await call(b,'preview',{fileId});
    assert.deepEqual(overlap.changes.filter(x=>x.conflict).map(x=>x.index),[],'Equal reported counts agree automatically');
    const syncId=randomUUID();
    const sync={fileId,copyRevision:overlap.copyRevision,masterRevision:overlap.masterRevision,resolutions:[],requestId:syncId};
    const synced=await call(b,'sync',sync);
    assert.deepEqual(await call(b,'sync',sync),synced);
    assert.deepEqual((await read(a,fileId,'original')).slice(0,3).map(x=>x.del_qty),[2,1,1]);
    assert.equal((await call(b,'preview',{fileId})).changes.length,0);
    const history=(await call(b,'history',{fileId})).history;
    assert.equal(history.length,2);
    assert.deepEqual(new Set(history.map(x=>x.profile_name)),new Set(['team_a','team_b']));
    assert.equal(objects.size,initialObjects.size,'Sync never rewrites Excel');
    assert.deepEqual(objects.get('excel-files/Large.xlsx'),initialObjects.get('excel-files/Large.xlsx'));
    const pinned=await call(b,'open',{fileId});
    await save(b,[edit(0,3)]);
    await assert.rejects(()=>call(b,'rows',{fileId,mode:'copy',offset:250,copyRevision:pinned.copyRevision}),/STALE_VERSION/);
    // A pending import is invisible and only its owner can append records.
    objects.set('excel-files/Partial.xlsx',fx.workbook(rows.slice(0,2)));
    const pending=await call(a,'import-start',{name:'Partial.xlsx',sourceKey:'Partial.xlsx'});
    await assert.rejects(()=>call(b,'import-batch',{fileId:pending.fileId,offset:0,rows:rows.slice(0,2)}),/INVALID_IMPORT/);
    await assert.rejects(()=>call(a,'import-batch',{fileId:pending.fileId,offset:1,rows:rows.slice(0,2)}),/INVALID_IMPORT_BATCH/);
    const batch={fileId:pending.fileId,offset:0,rows:rows.slice(0,2),requestId:randomUUID()};
    await call(a,'import-batch',batch); await call(a,'import-batch',batch);
    const resumed=await call(a,'import-start',{name:'Partial.xlsx',sourceKey:'Partial.xlsx'});
    assert.equal(resumed.rowCount,2);
    assert.equal((await call(a,'list')).files.length,1);
    await assert.rejects(()=>call(a,'open',{fileId:pending.fileId}),/FILE_NOT_FOUND/);
    await assert.rejects(()=>call(a,'import-finish',{fileId:pending.fileId,rowCount:3}),/INVALID_ROW_COUNT/);
    await call(a,'import-finish',{fileId:pending.fileId,rowCount:2});
    assert.equal((await call(a,'list')).files.length,2);
    // Two saves start with the same revision; only one may commit.
    const revision=(await copy(b)).revision;
    const race=await Promise.allSettled([call(b,'save',{fileId,copyRevision:revision,edits:[edit(0,1)]}),call(b,'save',{fileId,copyRevision:revision,edits:[edit(0,2)]})]);
    assert.equal(race.filter(x=>x.status==='fulfilled').length,1);
    assert.match(race.find(x=>x.status==='rejected').reason.message,/STALE_VERSION/);
    await save(b,rows.map((_,index)=>edit(index,3)));
    const largePreview=await call(b,'preview',{fileId});
    assert.equal(largePreview.pending,5364);
    assert.equal(largePreview.changes.length,250,'Review pages stay bounded for a full-route update');
    await call(b,'sync',{fileId,copyRevision:largePreview.copyRevision,masterRevision:largePreview.masterRevision,resolutions:[]});
    const bulkHistory=(await call(b,'history',{fileId})).history[0];
    assert.equal(bulkHistory.change_count,5364);
    const bulkDetails=await call(b,'history-changes',{fileId,eventId:bulkHistory.id,offset:5250});
    assert.equal(bulkDetails.changes.length,114,'Large audit trails are paginated');
    await save(b,[edit(0,0)]); assert.equal((await copy(b)).pending_count,1);
    await save(b,[edit(0,3)]); assert.equal((await copy(b)).pending_count,0,'Returning to baseline removes a draft');
    await save(a,[edit(1,1),edit(2,2)]);
    const decisions=await call(a,'preview',{fileId});
    assert.equal(decisions.changes.filter(x=>x.conflict).length,2);
    await call(a,'sync',{fileId,copyRevision:decisions.copyRevision,masterRevision:decisions.masterRevision,
      resolutions:[{index:1,choice:'mine'},{index:2,choice:'original'}]});
    const resolved=(await call(a,'rows',{fileId,mode:'original',masterRevision:(await original()).revision,offset:0})).rows;
    assert.equal(resolved[1].del_qty,1); assert.equal(resolved[2].del_qty,3);
    await pg.exec('set role authenticated');
    await assert.rejects(()=>pg.query('select * from cd_data_records'),/permission denied/);
    await assert.rejects(()=>pg.query("select public.cd_data_call($1,'team_a',null,'x','{}')",[a.id]),/permission denied/);
    await pg.exec('reset role');
    assert.equal(state.uploads.length,0);
    console.log('PASS: 5,364-row batched import, resumability, isolated sparse copies, atomic saves, stale pages, conflict sync, receipts, history, permissions, zero workbook writes.');
  } finally { await pg.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
